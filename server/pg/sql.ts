import { TABLES, type ColumnType, type TableName } from '../core/schema';

/** `updatedSeq` → `updated_seq`. */
export const snake = (s: string): string => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

/** Columns of a table besides `data`, in order, with their types. */
export function columns(table: TableName): [field: string, type: ColumnType][] {
  const spec = TABLES[table];
  const out = new Map<string, ColumnType>();
  for (const k of spec.key) out.set(k, 'text');
  for (const [k, t] of Object.entries(spec.index ?? {})) if (!out.has(k)) out.set(k, t);
  if (spec.owned) {
    if (!out.has('userId')) out.set('userId', 'text');
    out.set('updatedSeq', 'bigint');
  }
  return [...out];
}

function tableSql(name: TableName): string {
  const spec = TABLES[name];
  const cols = columns(name).map(([f, t]) => `  ${snake(f)} ${t}${spec.key.includes(f) || (spec.owned && (f === 'userId' || f === 'updatedSeq')) ? ' not null' : ''}`);
  const lines = [
    `create table if not exists public.${name} (`,
    [...cols, '  data jsonb not null', `  primary key (${spec.key.map(snake).join(', ')})`].join(',\n'),
    ');',
  ];
  if (spec.owned) lines.push(`create index if not exists ${name}_user_seq on public.${name} (user_id, updated_seq);`);
  for (const f of Object.keys(spec.index ?? {})) {
    if (spec.key.includes(f)) continue;
    lines.push(`create index if not exists ${name}_${snake(f)} on public.${name} (${snake(f)});`);
  }
  (spec.unique ?? []).forEach((cols, i) => lines.push(`create unique index if not exists ${name}_unique_${i + 1} on public.${name} (${cols.map(snake).join(', ')});`));
  lines.push(`alter table public.${name} enable row level security;`);
  return lines.join('\n');
}

/**
 * The SQL of migration `n` (`server/supabase/migrations`), generated from `server/core/schema.ts`
 * (`npm run server:sql`; a test keeps the committed files equal to this). Row-level security is on
 * with no policies: clients never touch tables, only the API (edge function) does (§4.2).
 */
export function migrationSql(n: number): string {
  const tables = (Object.keys(TABLES) as TableName[]).filter((t) => TABLES[t].migration === n);
  const parts = [
    `-- Sift server schema, migration ${n}. Generated by \`npm run server:sql\` from server/core/schema.ts. Do not edit by hand.`,
    '-- Every table: key and filter columns plus the whole row as `data`. Only the API edge function (database owner) reads and writes.',
    ...tables.map(tableSql),
  ];
  if (n === 1) {
    parts.push(
      "insert into public.app_config (key, data) values ('client', '{\"key\":\"client\",\"value\":{\"minSupportedApiVersion\":1}}') on conflict (key) do nothing;",
      '-- Supabase roles: no direct table access for app clients (defense in depth on top of RLS).',
      [
        'do $$',
        'begin',
        "  if exists (select 1 from pg_roles where rolname = 'anon') then",
        '    revoke all on all tables in schema public from anon, authenticated;',
        '  end if;',
        'end $$;',
      ].join('\n'),
    );
  }
  return `${parts.join('\n\n')}\n`;
}

/** Migration numbers in use, ascending. */
export const MIGRATIONS = [...new Set(Object.values(TABLES).map((t) => t.migration))].sort((a, b) => a - b);

/** Committed file name of migration `n`. */
export const migrationFile = (n: number): string => `2026102700000${n}_sift_${n === 1 ? 'core' : n === 2 ? 'social' : `m${n}`}.sql`;
