import { assemblePack, buildPack, type Atlas, type ContentPack, type PresetIds } from '../../../shared/content/pack';
import type { AtlasIndex } from '../../../shared/content/sprites';
import type { VoxelModel } from '../../../shared/content/model';

/**
 * The baseline content pack bundled with the app: every JSON file under `content/` plus every model.
 * Vite bundles the files at build time, so a new animal, skin, theme or building needs no code change:
 * add its folder or file (`npm run content:new`, docs/guides/CONTENT.md).
 */
const raw = import.meta.glob<unknown>(
  ['../../../content/**/*.json', '!../../../content/models/**', '!../../../content/sprites/**', '!../../../content/**/model.json'],
  { eager: true, import: 'default' },
);
// Sprite atlas (Step 3.5), generated by `npm run content:sprites`.
const atlasIndex = import.meta.glob<AtlasIndex>('../../../content/sprites/atlas.json', { eager: true, import: 'default' });
const atlasImage = import.meta.glob<string>('../../../content/sprites/atlas.png', { eager: true, query: '?url', import: 'default' });
// Models (Step 3.3): builder files (`.ts`) or MagicaVoxel imports (`.json`). An item folder's own model
// (`animals/fox/model.ts`) has the ref `animals/fox`; loose models (`models/overlays/hat.ts`) `overlays/hat`.
const jsonModels = import.meta.glob<VoxelModel>(['../../../content/*/*/model.json', '../../../content/models/**/*.json'], { eager: true, import: 'default' });
const builderModels = import.meta.glob<VoxelModel>(['../../../content/*/*/model.ts', '../../../content/models/**/*.ts'], { eager: true, import: 'default' });

const PREFIX = '../../../content/';
const META = new Set(['pack.json', 'presets.json']);

/** Model ref of a model file path relative to `content/` (`animals/fox/model.ts` → `animals/fox`). */
export function modelRef(path: string): string {
  return path.startsWith('models/') ? path.slice('models/'.length).replace(/\.(ts|json)$/, '') : path.replace(/\/model\.(ts|json)$/, '');
}

export function builtinModels(): Record<string, VoxelModel> {
  const out: Record<string, VoxelModel> = {};
  // A converted `.json` (MagicaVoxel) and a builder `.ts` for the same ref: the builder wins.
  for (const [p, model] of [...Object.entries(jsonModels), ...Object.entries(builderModels)]) out[modelRef(p.slice(PREFIX.length))] = model;
  return out;
}

export function contentFiles(): { path: string; data: unknown }[] {
  return Object.entries(raw)
    .map(([p, data]) => ({ path: p.slice(PREFIX.length), data }))
    .filter((f) => !META.has(f.path));
}

/** Preset ids the app's code implements (`content/presets.json`, Step 3.2). */
export const presetIds = raw[`${PREFIX}presets.json`] as PresetIds;

const index = atlasIndex[`${PREFIX}sprites/atlas.json`];
const image = atlasImage[`${PREFIX}sprites/atlas.png`];
export const baselineAtlas: Atlas | undefined = index && image ? { ...index, image } : undefined;

const source = {
  contentVersion: (raw[`${PREFIX}pack.json`] as { contentVersion: string }).contentVersion,
  files: contentFiles(),
  models: builtinModels(),
  presets: presetIds,
  ...(baselineAtlas ? { atlas: baselineAtlas } : {}),
};
const assembled = assemblePack(source);

/** Content problems (development builds keep running without the broken entries; the Studio lists them). */
export const baselineProblems: readonly string[] = assembled.problems;

/** Production builds fail on any problem; `content:validate` and the unit tests keep that from happening. */
export const baselinePack: ContentPack = import.meta.env.DEV ? assembled.pack : buildPack(source);
